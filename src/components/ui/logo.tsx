import { cn } from "@/lib/utils"
import { LOGO_ART } from "./logo-art"

type LogoVariant = "mini" | "mark" | "tile"

interface LogoProps {
  variant?: LogoVariant
  className?: string
  /** Accessible name; omit when the logo sits next to visible text (decorative). */
  label?: string
}

/**
 * RH monogram "a1" on a 64-unit square: three stems (R, the shared R-bowl/H-left, H right), a square R bowl,
 * one crossbar running from the R stem through the H, and a 45° leg to the foot of the shared stem.
 * "mini" is the glyph in currentColor; "mark" adds four crop marks in the mark colour on the trim lines;
 * "tile" reverses the glyph out of an ink square. Path data is generated by scripts/logo/make.mjs.
 */
export function Logo({ variant = "mini", className, label }: Readonly<LogoProps>) {
  const a11y = label ? { role: "img", "aria-label": label } : { "aria-hidden": true as const }

  return (
    <svg viewBox={variant === "mark" ? "-4 0 72 64" : "0 0 64 64"} className={cn("shrink-0", className)} {...a11y}>
      {variant === "tile" && <rect width="64" height="64" className="fill-ink" />}
      <path d={LOGO_ART.glyph} className={variant === "tile" ? "fill-paper" : undefined} fill="currentColor" />
      {variant === "mark" && <path d={LOGO_ART.marks} fill="none" className="stroke-mark" strokeWidth={1.5} />}
    </svg>
  )
}
