// RH monogram "a1": the single geometry source for every logo file. Usage: node scripts/logo/make.mjs
// Outputs are committed; rerun after changing GLYPH, MARKS or the PRINT_HEX colours.
// One ink: cobalt on cream, cream on night. Colours are written as rgb() because the grep gate bans hex literals in src/.
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { PRINT_HEX } from '../../src/lib/print-hex.ts'

// 64-unit square, 16px grid (4 units = 1px at 16). Stems R / shared / H-right, R bowl top bar,
// one crossbar from the R stem to the H stem, 45° leg to the foot of the shared stem.
// The leg's edges sit half a pixel off the grid, so at 16px it rasterises as an anti-aliased stair.
export const GLYPH = 'M4 8h8v48H4z M28 8h8v48h-8z M52 8h8v48h-8z M4 8h32v8H4z M4 28h56v8H4z M8 32h2l22 22v2h-6L8 38z'
// Four L-ticks on the glyph's trim lines (box 4,8 to 60,56), for the "mark" viewBox -4 0 72 64.
export const MARKS = 'M-3 8h4 M4 1v4 M63 8h4 M60 1v4 M-3 56h4 M4 59v4 M63 56h4 M60 59v4'

const ROOT = fileURLToPath(new URL('../../', import.meta.url))
const sharp = createRequire(ROOT + 'package.json')('sharp')
const rgb = hex => `rgb(${[1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16)).join(' ')})`
const { ink: INK, paper: PAPER, night: NIGHT, nightInk: NIGHT_INK } = PRINT_HEX
const LIGHT = { ink: rgb(INK), paper: rgb(PAPER) }
const DARK = { ink: rgb(NIGHT_INK), paper: rgb(NIGHT) }
const svg = (viewBox, body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><title>Rizky Haksono</title>${body}</svg>\n`
const glyph = (fill, attrs = '') => `<path fill="${fill}"${attrs} d="${GLYPH}"/>`
// The ticks are the same ink at 60%: one ink, no second hue.
const marks = ink => `<path fill="none" stroke="${ink}" stroke-opacity="0.6" stroke-width="1.5" d="${MARKS}"/>`

const mark = ({ ink, paper }) => svg('-4 0 72 64', `<rect x="-4" width="72" height="64" fill="${paper}"/>${glyph(ink)}${marks(ink)}`)
const tile = ({ ink, paper }, inset = 1) =>
  svg('0 0 64 64', `<rect width="64" height="64" fill="${ink}"/>${glyph(paper, inset === 1 ? '' : ` transform="translate(${32 * (1 - inset)} ${32 * (1 - inset)}) scale(${inset})"`)}`)
// Plus Jakarta Sans 600 cap height is .745em (measured on the H): cap height = half the glyph (24) so size = 24 / .745 = 32.2,
// cap centre on the glyph centre (32) so baseline = 32 + 12 = 44, gap = one counter (16). The name is 6.70em wide at -0.02em, so the box is 300.
// shortcut: live <text>, so it falls back to a system sans where Plus Jakarta Sans is not installed; outline it if the lockup ships anywhere.
const lockup = ({ ink, paper }) => svg('0 0 300 64', `<rect width="300" height="64" fill="${paper}"/>${glyph(ink)}`
  + `<text x="76" y="44" fill="${ink}" font-family="'Plus Jakarta Sans', system-ui, sans-serif" font-weight="600" font-size="32.2" letter-spacing="-0.64">Rizky Haksono</text>`)

const written = []
const write = (rel, data) => { writeFileSync(ROOT + rel, data); written.push(`${rel} (${data.length} B)`) }

mkdirSync(ROOT + 'public/brand', { recursive: true })
for (const [theme, c] of [['light', LIGHT], ['dark', DARK]]) {
  write(`public/brand/mark-${theme}.svg`, mark(c))
  write(`public/brand/tile-${theme}.svg`, tile(c))
  write(`public/brand/lockup-${theme}.svg`, lockup(c))
}
// For satori on the paper ground of the OG and certificate images: no background.
write('public/brand/og-mark.svg', svg('-4 0 72 64', glyph(LIGHT.ink) + marks(LIGHT.ink)))
write('src/app/icon.svg', tile(LIGHT))
write('src/components/ui/logo-art.ts', '// Generated by scripts/logo/make.mjs. Do not edit by hand.\n'
  + `export const LOGO_ART = ${JSON.stringify({ glyph: GLYPH, marks: MARKS }, null, 2)} as const\n`)

// Rasterised straight at the target size: the 4-unit grid lands on whole pixels at 16 and 32.
const png = (svgText, size) => sharp(Buffer.from(svgText), { density: 72 * size / 64 }).resize(size, size).png().toBuffer()
// iOS rounds the corners, so the glyph sits at 70% of the tile.
write('src/app/apple-icon.png', await png(tile(LIGHT, 0.7), 180))

// PNG-in-ICO: ICONDIR (6 B), one 16 B ICONDIRENTRY per image, then the PNG blobs.
const icons = await Promise.all([16, 32].map(async size => ({ size, data: await png(tile(LIGHT), size) })))
const head = Buffer.alloc(6 + 16 * icons.length)
head.writeUInt16LE(0, 0); head.writeUInt16LE(1, 2); head.writeUInt16LE(icons.length, 4)
let offset = head.length
icons.forEach(({ size, data }, i) => {
  const e = 6 + 16 * i
  head.writeUInt8(size, e); head.writeUInt8(size, e + 1) // colour count and reserved stay 0
  head.writeUInt16LE(1, e + 4); head.writeUInt16LE(32, e + 6) // planes, bits per pixel
  head.writeUInt32LE(data.length, e + 8); head.writeUInt32LE(offset, e + 12)
  offset += data.length
})
write('src/app/favicon.ico', Buffer.concat([head, ...icons.map(i => i.data)]))
const ico = readFileSync(ROOT + 'src/app/favicon.ico')
if (!ico.subarray(0, 6).equals(Buffer.from([0, 0, 1, 0, 2, 0]))) throw new Error('favicon.ico header is not 00 00 01 00 02 00')

console.log('wrote\n  ' + written.join('\n  '))
